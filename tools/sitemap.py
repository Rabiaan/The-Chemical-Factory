#!/usr/bin/env python
"""Regenerate sitemap.xml so it cannot drift from the pages that exist.

Every static page is listed, plus one entry per product because
product-detail.html?id=<product> is a distinct indexable page. Placeholders
that are not real pages (privacy/terms/cookie until they exist) are skipped
automatically.

Run:  python tools/sitemap.py
Then: replace SITE-URL-PLACEHOLDER with the live origin.
"""
import glob
import io
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

PLACEHOLDER = "SITE-URL-PLACEHOLDER"
BASE = "https://the-chemical-factory.netlify.app"   # dev-only; overridden below

# Deliberate exclusions and why.
SKIP = {
    "product-detail.html": "handled per-product below",
}

PRIORITY = {
    "index.html": "1.0", "products.html": "0.9", "services.html": "0.8",
    "projects.html": "0.8", "about.html": "0.7", "contact.html": "0.7",
    "datasheets.html": "0.7", "clients.html": "0.6",
    "privacy.html": "0.2", "terms.html": "0.2", "cookie.html": "0.2",
}


def is_noindex(page):
    """A noindex page must not appear in the sitemap - the two would contradict."""
    try:
        src = io.open(page, encoding="utf-8").read()
    except IOError:
        return False
    m = re.search(r'<meta name="robots" content="([^"]*)"', src)
    return bool(m) and "noindex" in m.group(1)


def product_ids():
    src = io.open("js/products-data.js", encoding="utf-8").read()
    return re.findall(r"^ {6}id: '([a-z0-9][a-z0-9-]*)',", src, re.M)


def main():
    url_base = os.environ.get("SITE_URL", PLACEHOLDER)
    excluded = []
    pages = []
    for p in sorted(glob.glob("*.html")):
        if p in SKIP:
            continue
        if is_noindex(p):
            excluded.append(p)
            continue
        pages.append(p)

    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           "<!-- Generated by tools/sitemap.py - do not edit by hand. -->",
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']

    for p in pages:
        pr = PRIORITY.get(p, "0.5")
        freq = "weekly" if p == "index.html" else "monthly"
        out += ["  <url>",
                f"    <loc>{url_base}/{p}</loc>",
                f"    <changefreq>{freq}</changefreq>",
                f"    <priority>{pr}</priority>",
                "  </url>"]

    for pid in product_ids():
        out += ["  <url>",
                f"    <loc>{url_base}/product-detail.html?id={pid}</loc>",
                "    <changefreq>monthly</changefreq>",
                "    <priority>0.8</priority>",
                "  </url>"]

    out.append("</urlset>")
    xml = "\n".join(out) + "\n"
    io.open("sitemap.xml", "w", encoding="utf-8", newline="\n").write(xml)

    print("sitemap.xml written: %d pages + %d products = %d urls"
          % (len(pages), len(product_ids()), len(pages) + len(product_ids())))
    print("base url: %s" % url_base)
    if excluded:
        print("skipped (noindex drafts, not listed until approved): %s"
              % ", ".join(excluded))
    if PLACEHOLDER in xml:
        print("\nTODO: replace SITE-URL-PLACEHOLDER in sitemap.xml and robots.txt")
        print("      with the live origin once the domain is known.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
